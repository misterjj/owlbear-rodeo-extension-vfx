const DICTIONARIES = { fr, en };
export type Language = keyof typeof DICTIONARIES;
export const LANGUAGES = Object.keys(DICTIONARIES) as Language[];
/** Nom de chaque langue, écrit dans cette langue. */
export const LANGUAGE_NAMES: Record<Language, string> = { fr: "Français", en: "English" };

const LANGUAGE_KEY = "vfx:langue";
let forced: Language | undefined;

const isLanguage = (value: unknown): value is Language => LANGUAGES.includes(value as Language);

/** La langue choisie, ou « auto » pour suivre le navigateur. */
export function languageSetting(): Language | "auto" {
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    return isLanguage(saved) ? saved : "auto";
  } catch {
    return "auto";
  }
}

export function setLanguageSetting(language: Language | "auto") {
  try {
    if (language === "auto") localStorage.removeItem(LANGUAGE_KEY);
    else localStorage.setItem(LANGUAGE_KEY, language);
  } catch (error) {
    console.warn("Effets :", error);
  }
}

/** Le français pour un navigateur français, l'anglais pour tous les autres. */
export function browserLanguage(tags: readonly string[]): Language {
  for (const tag of tags) {
    const base = tag.toLowerCase().split("-")[0];
    if (isLanguage(base)) return base;
  }
  return "en";
}

export function currentLanguage(): Language {
  if (forced) return forced;
  const setting = languageSetting();
  if (setting !== "auto") return setting;
  return browserLanguage(typeof navigator === "undefined" ? [] : navigator.languages ?? []);
}

/** Pour les tests : les textes attendus ne dépendent pas de la machine. */
export function forceLanguage(language: Language | undefined) {
  forced = language;
}

export function t(key: TextKey, values: Record<string, string | number> = {}) {
  return DICTIONARIES[currentLanguage()][key].replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in values ? String(values[name]) : whole,
  );
}

export const DICTIONARY_KEYS = Object.keys(fr) as TextKey[];
export const dictionary = (language: Language) => DICTIONARIES[language];
